#!/usr/bin/env python3
"""build-paragraph-catalog.py — what paragraphs of each type were observed to do.

Spectra change add-paragraph-moves. From annotated sidecars it writes a YAML file
with, for each paragraph type: how many paragraphs per label, which moves open
them, and what follows each move (the next move or END, the next proposition's
relation, the move of the next proposition's head), counted per label. A relation
of ROOT means the next proposition is the paragraph's root; `head_move` is null
when that proposition has no head or its head has no move.

The file records paths that were observed. It is not a rule, and nothing reads it
to judge a manuscript. It holds no ledger text, no proposition ids, no paragraph
ids and no paths, because it ships in a public plugin and the sidecars may not.

Usage:
    python3 build-paragraph-catalog.py --sidecars empirical=DIR [--sidecars default=DIR ...]
        --out paragraph-catalog.yaml [--vocabulary vocabulary.yaml] [--check]

DIR is a ledger directory holding main.jsonl, structure.json and discourse.jsonl.
Directories under one label add up.

Exit code:
    0 — written, or --check found the file current
    1 — --check found the file stale or missing; nothing was written
    2 — an input is missing or invalid, a value is not in the vocabulary, or the
        sidecars fail S1, S2, S3 or the plan of S5
"""
from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from _lib.move_vocabulary import Vocabulary, load_vocabulary, require_yaml  # noqa: E402

EXIT_OK, EXIT_STALE, EXIT_USAGE = 0, 1, 2
LABEL = re.compile(r"[a-z0-9][a-z0-9-]*")
END, ROOT = "END", "ROOT"
HEADER = (
    "# Generated by build-paragraph-catalog.py. Do not edit: rerun it from annotated sidecars.\n"
    "# Paths observed in annotated manuscripts, counted per label. A record of what was seen, not a rule.\n"
)


def _load_state():
    spec = importlib.util.spec_from_file_location("structure_state", Path(__file__).parent / "structure-state.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


state = _load_state()
vs = state.vs


def parse_source(raw: str) -> tuple[str, Path]:
    label, sep, directory = raw.partition("=")
    if not sep or not directory or not LABEL.fullmatch(label):
        raise vs.InputError(f"--sidecars {raw!r} is not <label>=<directory> with a lowercase label")
    return label, Path(directory)


def _checked_values(analysis, raw_pars: dict, vocabulary: Vocabulary, directory: Path) -> None:
    for rec in analysis.records:
        move = rec.data.get("move")
        if move is not None and move not in vocabulary.moves:
            raise vs.InputError(f"{directory}: move {move!r} is not in the vocabulary")
    for par in raw_pars.values():
        kind = par.get("type")
        if kind is not None and kind not in vocabulary.paragraph_types:
            raise vs.InputError(f"{directory}: paragraph type {kind!r} is not in the vocabulary")


def _next_option(records: list, by_id: dict, position: int) -> tuple:
    """(move, relation, head move) of the proposition at `position`."""
    data = records[position - 1].data
    has_head = "head" in data and data["head"] != "pending"
    head = by_id.get(data.get("head")) if has_head else None
    relation = data.get("relation") if has_head else ROOT
    return data.get("move"), relation, head.get("move") if head else None


def collect(label: str, directory: Path, vocabulary: Vocabulary, tally: dict) -> None:
    """Add one manuscript's paragraphs to the running tally."""
    analysis = state.load_checked(directory / "main.jsonl", directory / "structure.json", directory / "discourse.jsonl")
    raw_pars = {p["id"]: p for p in analysis.structure["paragraphs"]}
    _checked_values(analysis, raw_pars, vocabulary, directory)
    records, pars = analysis.records, analysis.paragraphs
    by_id = {r.data.get("prop_id"): r.data for r in records}
    tally["sources"][label] += 1
    tally["no_move"][label] += sum("move" not in r.data for r in records)
    for i, par in enumerate(pars):
        kind = raw_pars[par.pid].get("type")
        if kind is None:
            tally["no_type"][label] += 1
            continue
        tally["paragraphs"][(kind, label)] += 1
        end = pars[i + 1].first if i + 1 < len(pars) else len(records) + 1
        opening = records[par.first - 1].data.get("move")
        if opening is not None:
            tally["opening"][(kind, opening, label)] += 1
        for pos in range(par.first, end):
            move = records[pos - 1].data.get("move")
            if move is None:
                continue
            if pos + 1 == end:
                tally["next"][(kind, move, END, None, None, label)] += 1
                continue
            next_move, relation, head_move = _next_option(records, by_id, pos + 1)
            if next_move is not None:
                tally["next"][(kind, move, next_move, relation, head_move, label)] += 1


def _counts(pairs: dict[str, int]) -> dict[str, int]:
    return dict(sorted(pairs.items()))


def assemble(tally: dict) -> dict:
    labels = sorted(tally["sources"])
    types: dict = {}
    for (kind, label), n in tally["paragraphs"].items():
        entry = types.setdefault(kind, {"paragraphs": {}, "opening_moves": {}, "moves": {}})
        entry["paragraphs"][label] = n
    for (kind, move, label), n in tally["opening"].items():
        types[kind]["opening_moves"].setdefault(move, {})[label] = n
    options: dict = {}
    for (kind, move, nxt, relation, head_move, label), n in tally["next"].items():
        options.setdefault((kind, move), {}).setdefault((nxt, relation, head_move), {})[label] = n
    for (kind, move), found in options.items():
        rows = []
        for (nxt, relation, head_move), counts in sorted(found.items(), key=lambda kv: (-sum(kv[1].values()), str(kv[0]))):
            row = {"move": nxt, "counts": _counts(counts)} if nxt == END else {
                "move": nxt, "relation": relation, "head_move": head_move, "counts": _counts(counts)}
            rows.append(row)
        types[kind]["moves"].setdefault(move, {})["next"] = rows
    for entry in types.values():
        entry["paragraphs"] = _counts(entry["paragraphs"])
        entry["opening_moves"] = {m: _counts(c) for m, c in sorted(entry["opening_moves"].items())}
        entry["moves"] = dict(sorted(entry["moves"].items()))
    return {
        "sources": {label: tally["sources"][label] for label in labels},
        "excluded": {
            "propositions_without_move": {label: tally["no_move"][label] for label in labels},
            "paragraphs_without_type": {label: tally["no_type"][label] for label in labels},
        },
        "paragraph_types": dict(sorted(types.items())),
    }


def render(sources: list[tuple[str, Path]], vocabulary_path: Path | None) -> str:
    yaml = require_yaml()
    vocabulary = load_vocabulary(vocabulary_path)
    tally = {name: Counter() for name in ("sources", "no_move", "no_type", "paragraphs", "opening", "next")}
    for label, directory in sources:
        collect(label, directory, vocabulary, tally)
    body = yaml.safe_dump(assemble(tally), sort_keys=False, allow_unicode=True, default_flow_style=False)
    return HEADER + body


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Build the catalog of observed paragraph paths from annotated sidecars.")
    p.add_argument("--sidecars", action="append", required=True, metavar="LABEL=DIR", help="a label and a ledger directory")
    p.add_argument("--out", type=Path, required=True, help="the catalog file")
    p.add_argument("--vocabulary", type=Path, help="vocabulary.yaml (default: the one shipped with the plugin)")
    p.add_argument("--check", action="store_true", help="write nothing; exit 1 when the file differs from what would be written")
    args = p.parse_args(argv)
    try:
        text = render(sorted(map(parse_source, args.sidecars), key=lambda s: s[0]), args.vocabulary)
    except (vs.InputError, state.StructureError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_USAGE
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.is_file() else None
        if current != text:
            print(f"stale: {args.out} differs from what the sidecars produce")
            return EXIT_STALE
        print(f"current: {args.out}")
        return EXIT_OK
    args.out.write_text(text, encoding="utf-8")
    print(f"written: {args.out}")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
